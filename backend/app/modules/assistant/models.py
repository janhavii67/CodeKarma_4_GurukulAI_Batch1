class ChatConversation(Base):
    """
    User conversation session with the AI assistant.
    Bound to a specific user and optional machine or process context.
    """
    __tablename__ = "chat_conversations"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=generate_uuid)
    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    title: Mapped[str] = mapped_column(String(255), default="New Conversation", nullable=False)
    machine_id: Mapped[Optional[str]] = mapped_column(String(36), ForeignKey("machines.id", ondelete="SET NULL"), nullable=True, index=True)
    process_id: Mapped[Optional[str]] = mapped_column(String(36), ForeignKey("manufacturing_processes.id", ondelete="SET NULL"), nullable=True, index=True)
    status: Mapped[str] = mapped_column(String(32), default=CONVERSATION_STATUS_ACTIVE, nullable=False, index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, onupdate=utc_now, nullable=False)

    # Relationships
    user = relationship("User", foreign_keys=[user_id])
    machine = relationship("Machine", foreign_keys=[machine_id])
    process = relationship("ManufacturingProcess", foreign_keys=[process_id])
    messages: Mapped[List["ChatMessage"]] = relationship(
        "ChatMessage",
        back_populates="conversation",
        cascade="all, delete-orphan",
        order_by="ChatMessage.created_at",
    )


class TutorMemory(Base):
    """Private learner context explicitly saved by its owner for future Tutor chats."""
    __tablename__ = "tutor_memories"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=generate_uuid)
    user_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    category: Mapped[str] = mapped_column(String(32), nullable=False, default="learning_goal")
    content: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, onupdate=utc_now, nullable=False)

    user = relationship("User", foreign_keys=[user_id])


class ChatMessage(Base):
    """
    Individual turn within an assistant chat conversation.
    Tracks whether generated by AI, provider metadata, and evidence status.
    """
    __tablename__ = "chat_messages"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=generate_uuid)
    conversation_id: Mapped[str] = mapped_column(String(36), ForeignKey("chat_conversations.id", ondelete="CASCADE"), nullable=False, index=True)
    role: Mapped[str] = mapped_column(String(16), nullable=False)  # user / assistant
    content: Mapped[str] = mapped_column(Text, nullable=False)
    is_ai_generated: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    evidence_status: Mapped[str] = mapped_column(String(32), default=EVIDENCE_STATUS_NA, nullable=False)
    provider_name: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)
    model_name: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)
    prompt_version: Mapped[Optional[str]] = mapped_column(String(32), nullable=True)
    latency_ms: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    request_id: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)
    # Links an audio-grounded answer to its non-retained analysis record. The
    # result payload is reconstructed from current approved data when history loads.
    audio_analysis_job_id: Mapped[Optional[str]] = mapped_column(
        String(36), nullable=True
    )
    attachment_media_id: Mapped[Optional[str]] = mapped_column(
        String(36), ForeignKey("media_assets.id", ondelete="SET NULL"), nullable=True, index=True
    )
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    # Relationships
    conversation = relationship("ChatConversation", back_populates="messages", foreign_keys=[conversation_id])
    message_sources: Mapped[List["ChatMessageSource"]] = relationship(
        "ChatMessageSource",
        back_populates="message",
        cascade="all, delete-orphan",
        order_by="ChatMessageSource.rank",
    )
    feedback: Mapped[List["AssistantFeedback"]] = relationship(
        "AssistantFeedback",
        back_populates="message",
        cascade="all, delete-orphan",
    )


class KnowledgeSource(Base):
    """
    Indexable document or version source referenced by the RAG assistant.
    Encapsulates knowledge versions, procedures, transcripts, etc.
    """
    __tablename__ = "knowledge_sources"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=generate_uuid)
    source_type: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    source_ref_id: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    knowledge_version_id: Mapped[Optional[str]] = mapped_column(String(36), ForeignKey("knowledge_versions.id", ondelete="CASCADE"), nullable=True, index=True)
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    machine_id: Mapped[Optional[str]] = mapped_column(String(36), ForeignKey("machines.id", ondelete="SET NULL"), nullable=True, index=True)
    process_id: Mapped[Optional[str]] = mapped_column(String(36), ForeignKey("manufacturing_processes.id", ondelete="SET NULL"), nullable=True, index=True)
    product_family: Mapped[Optional[str]] = mapped_column(String(128), nullable=True, index=True)
    status: Mapped[str] = mapped_column(String(32), default="published", nullable=False, index=True)
    access_policy_ref: Mapped[Optional[str]] = mapped_column(String(128), nullable=True)
    indexed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)
    index_version: Mapped[str] = mapped_column(String(32), default="v1", nullable=False)

    # Relationships
    knowledge_version = relationship("KnowledgeVersion", foreign_keys=[knowledge_version_id])
    machine = relationship("Machine", foreign_keys=[machine_id])
    process = relationship("ManufacturingProcess", foreign_keys=[process_id])
    chunks: Mapped[List["KnowledgeChunk"]] = relationship(
        "KnowledgeChunk",
        back_populates="source",
        cascade="all, delete-orphan",
        order_by="KnowledgeChunk.chunk_index",
    )


class KnowledgeChunk(Base):
    """
    Indexed text chunk belonging to a knowledge source.
    Includes chunk index, tokens, section labels, and timestamps for transcripts.
    """
    __tablename__ = "knowledge_chunks"
    __table_args__ = (
        UniqueConstraint("source_id", "chunk_index", name="uq_knowledge_chunks_source_idx"),
    )

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=generate_uuid)
    source_id: Mapped[str] = mapped_column(String(36), ForeignKey("knowledge_sources.id", ondelete="CASCADE"), nullable=False, index=True)
    chunk_index: Mapped[int] = mapped_column(Integer, nullable=False)
    text: Mapped[str] = mapped_column(Text, nullable=False)
    section_label: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    timestamp_start: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    timestamp_end: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    token_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    search_vector: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    metadata_json: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False, index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    # Relationships
    source = relationship("KnowledgeSource", back_populates="chunks", foreign_keys=[source_id])


class ChatMessageSource(Base):
    """
    Association linking a chat assistant message to the knowledge chunk(s) retrieved and cited.
    """
    __tablename__ = "chat_message_sources"

    message_id: Mapped[str] = mapped_column(String(36), ForeignKey("chat_messages.id", ondelete="CASCADE"), primary_key=True)
    chunk_id: Mapped[str] = mapped_column(String(36), ForeignKey("knowledge_chunks.id", ondelete="CASCADE"), primary_key=True)
    source_id: Mapped[str] = mapped_column(String(36), ForeignKey("knowledge_sources.id", ondelete="CASCADE"), nullable=False, index=True)
    rank: Mapped[int] = mapped_column(Integer, nullable=False)
    score: Mapped[float] = mapped_column(Float, default=0.0, nullable=False)
    cited: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)

    # Relationships
    message = relationship("ChatMessage", back_populates="message_sources", foreign_keys=[message_id])
    chunk = relationship("KnowledgeChunk", foreign_keys=[chunk_id])
    source = relationship("KnowledgeSource", foreign_keys=[source_id])


class AssistantFeedback(Base):
    """
    User feedback on assistant messages for triage, review, and continuous evaluation.
    """
    __tablename__ = "assistant_feedback"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=generate_uuid)
    message_id: Mapped[str] = mapped_column(String(36), ForeignKey("chat_messages.id", ondelete="CASCADE"), nullable=False, index=True)
    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    rating: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)  # 1-5 scale
    category: Mapped[str] = mapped_column(String(32), nullable=False, index=True)
    comment: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    status: Mapped[str] = mapped_column(String(32), default=FEEDBACK_STATUS_NEW, nullable=False, index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utc_now, nullable=False)

    # Relationships
    message = relationship("ChatMessage", back_populates="feedback", foreign_keys=[message_id])
    user = relationship("User", foreign_keys=[user_id])
