import sys
import os
sys.path.insert(0, os.path.abspath("."))
sys.path.insert(0, os.path.abspath("backend"))

import app.models
from app.db.session import SessionLocal
from app.core.config import settings
from app.modules.assistant.services.retrieval_service import RetrievalService, RetrievalQuery
from app.modules.assistant.prompts.prompt_builder import PromptBuilder
from app.modules.assistant.providers.llm_gemini import GeminiLLMProvider
from app.modules.assistant.validation.answer_validator import AnswerValidator

db = SessionLocal()
admin_user = db.query(app.models.user.User).filter(app.models.user.User.email == "admin@demo.local").first()
assert admin_user is not None, "Admin user not found"
admin_id = admin_user.id
provider = GeminiLLMProvider()
builder = PromptBuilder()
validator = AnswerValidator()

questions = [
    "What are the kinematic advantages and flexion limit of Biorad Excel MPK knee system?",
    "What is the validated indwelling duration and material of Biorad Pretoflex Double J stent?",
    "What is the recipe and baking temperature for traditional sourdough bread?",
]

for i, q in enumerate(questions, 1):
    print(f"\n==========================================")
    print(f"SMOKE TEST QUESTION {i}: {q}")
    print(f"==========================================")
    chunks = RetrievalService.retrieve_chunks(
        RetrievalQuery(query=q, user_id=admin_id, top_k=4),
        db=db,
    )
    print(f"Retrieved candidate chunks: {len(chunks)}")
    for c in chunks:
        print(f"  - [{c.chunk_id}] {c.title} (score: {c.score:.2f})")

    if not chunks:
        print("Outcome: Zero chunks -> insufficient_evidence=True")
        continue

    llm_req = builder.build_llm_request(question=q, chunks=chunks)
    resp = provider.generate(llm_req)
    val = validator.validate(resp.content, chunks)

    # Check whether the answer contains sufficient information or declares insufficient
    is_insufficient = (val.evidence_status == "insufficient") or (len(val.cited_chunk_ids) == 0)

    print(f"Answer generated by Gemini: {len(resp.content)} characters")
    print(f"Grounded Valid Citations: {val.cited_chunk_ids}")
    print(f"Evidence Status: {val.evidence_status}")
    print(f"Insufficient Evidence: {is_insufficient}")
    print(f"Answer Summary: {val.sanitized_content.replace(chr(10), ' ')[:220]}...")
